"""Render the dbt model DAG as Mermaid from a parsed manifest (S12).

The renderer is intentionally pure and deterministic: models are grouped by
their layer directory, sorted by name, and the edges are sorted too, so a fresh
``dbt parse`` produces byte-identical documentation in CI.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

_LAYER_ORDER = ("staging", "intermediate", "marts")
_UNKNOWN_LAYER = "other"
_MIN_MODEL_PATH_PARTS = 3


def _layer(node: Mapping[str, Any]) -> str:
    # dbt writes OS-native separators in ``original_file_path``; normalize them
    # so the rendered layer groups are identical on Linux, macOS and Windows.
    parts = str(node.get("original_file_path", "")).replace("\\", "/").split("/")
    if len(parts) >= _MIN_MODEL_PATH_PARTS and parts[0] == "models":
        return parts[1]
    return _UNKNOWN_LAYER


def _model_nodes(manifest: Mapping[str, Any]) -> dict[str, Mapping[str, Any]]:
    nodes = manifest.get("nodes", {})
    if not isinstance(nodes, Mapping):
        return {}
    return {
        str(unique_id): node
        for unique_id, node in nodes.items()
        if isinstance(node, Mapping)
        and node.get("resource_type") == "model"
        and node.get("package_name") == "ecuador_lakehouse"
    }


def _layer_sort_key(layer: str) -> tuple[int, str]:
    if layer in _LAYER_ORDER:
        return (_LAYER_ORDER.index(layer), layer)
    return (len(_LAYER_ORDER), layer)


def render_mermaid(manifest: Mapping[str, Any]) -> str:
    """Return a fenced ``mermaid`` flowchart of every model and dependency."""
    models = _model_nodes(manifest)
    by_name = {unique_id: str(node.get("name", unique_id)) for unique_id, node in models.items()}
    layers: dict[str, list[str]] = {}
    for unique_id, node in models.items():
        layers.setdefault(_layer(node), []).append(str(node.get("name", unique_id)))

    edges: set[tuple[str, str]] = set()
    for unique_id, node in models.items():
        child = str(node.get("name", unique_id))
        depends_on = node.get("depends_on", {})
        parents = depends_on.get("nodes", []) if isinstance(depends_on, Mapping) else []
        for parent_id in parents:
            parent_name = by_name.get(str(parent_id))
            if parent_name is not None:
                edges.add((parent_name, child))

    lines = ["```mermaid", "flowchart LR"]
    for layer in sorted(layers, key=_layer_sort_key):
        lines.append(f"  subgraph {layer}")
        for name in sorted(layers[layer]):
            lines.append(f'    {name}["{name}"]')
        lines.append("  end")
    for parent, child in sorted(edges):
        lines.append(f"  {parent} --> {child}")
    lines.append("```")
    return "\n".join(lines) + "\n"


def render_lineage_markdown(manifest: Mapping[str, Any]) -> str:
    """Return the committed ``docs/LINEAGE.md`` document for ``manifest``."""
    header = (
        "# dbt lineage\n"
        "\n"
        "Generated by `lakehouse docs --mermaid docs/LINEAGE.md` from a fresh\n"
        "`dbt parse`. Do not edit by hand.\n"
        "\n"
    )
    return header + render_mermaid(manifest)


class LineageMermaidRenderer:
    """``LineageRenderer`` adapter that renders the manifest with Mermaid."""

    def render_markdown(self, manifest: Mapping[str, Any]) -> str:
        """Render the complete lineage document."""
        return render_lineage_markdown(manifest)
