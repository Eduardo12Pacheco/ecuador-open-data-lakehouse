"""dbt adapter: run the packaged project through the in-process ``dbtRunner`` (D2, D18).

Every invocation receives absolute project, profile, target and log paths so
dbt never writes inside the repository or the installed package. dbt failures
are translated into the typed errors the CLI maps to exit codes:
:class:`TransformError` for broken runs and :class:`QualityGateError` for a
closed quality gate (the latter is raised by the use case that inspects the
returned :class:`QualitySummary`).
"""

from __future__ import annotations

import logging
import os
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any
from unittest.mock import patch

from dbt.adapters.duckdb.connections import DuckDBConnectionManager
from dbt.cli.main import dbtRunner

from ecuador_lakehouse.adapters.transform.project import copy_project, write_profiles
from ecuador_lakehouse.adapters.transform.results import load_json, parse_run_results
from ecuador_lakehouse.domain.errors import TransformError
from ecuador_lakehouse.domain.quality import QualitySummary

_ANONYMOUS_USAGE_POLICY = {"DBT_SEND_ANONYMOUS_USAGE_STATS": "false"}
_DBT_LOGGER_NAMES = ("file_log", "stdout_log")


class DbtTransformer:
    """``Transformer`` adapter backed by dbt-core and dbt-duckdb."""

    def __init__(
        self,
        *,
        warehouse_path: Path,
        home: Path,
        threads: int = 4,
        dbt_project_dir: Path | None = None,
    ) -> None:
        self._warehouse_path = Path(warehouse_path)
        self._home = Path(home)
        self._threads = threads
        self._dbt_dir = self._home / "dbt"
        self._project_dir = dbt_project_dir or (self._dbt_dir / "project")
        self._target_dir = self._dbt_dir / "target"
        self._log_dir = self._dbt_dir / "logs"

    @property
    def project_dir(self) -> Path:
        """Directory where the packaged project is materialized."""
        return self._project_dir

    @property
    def target_dir(self) -> Path:
        """Directory where dbt writes ``manifest.json`` and ``run_results.json``."""
        return self._target_dir

    def seed_and_run(self, *, select: str | None = None) -> None:
        """Run ``dbt seed`` then ``dbt run`` for the selected models."""
        self._prepare()
        self._run_command(["seed"], allow_failure=False)
        args = ["run"]
        if select:
            args.extend(["--select", select])
        self._run_command(args, allow_failure=False)

    def test(self, *, select: str | None = None) -> QualitySummary:
        """Run selected dbt data and unit tests and return the parsed summary."""
        self._prepare()
        args = ["test"]
        if select:
            args.extend(["--select", select])
        self._run_command(args, allow_failure=True)
        run_results = load_json(self._target_dir / "run_results.json")
        manifest = self._load_manifest()
        return parse_run_results(run_results, manifest)

    def manifest(self) -> Mapping[str, Any]:
        """Return the manifest generated by the last dbt invocation."""
        return self._load_manifest()

    def close(self) -> None:
        """dbt runs are process-local; nothing to release."""
        return None

    def _load_manifest(self) -> Mapping[str, Any]:
        return load_json(self._target_dir / "manifest.json")

    def _prepare(self) -> None:
        copy_project(self._project_dir)
        write_profiles(
            self._project_dir,
            warehouse_path=self._warehouse_path,
            threads=self._threads,
        )

    def _command_args(self, command: str, extra: Sequence[str]) -> list[str]:
        return [
            command,
            *extra,
            "--project-dir",
            str(self._project_dir.resolve()),
            "--profiles-dir",
            str(self._project_dir.resolve()),
            "--target-path",
            str(self._target_dir.resolve()),
            "--log-path",
            str(self._log_dir.resolve()),
            "--no-use-colors",
        ]

    def _run_command(self, args: Sequence[str], *, allow_failure: bool) -> None:
        run_results_path = self._target_dir / "run_results.json"
        run_results_path.parent.mkdir(parents=True, exist_ok=True)
        run_results_path.unlink(missing_ok=True)
        command = self._command_args(args[0], args[1:])
        try:
            with patch.dict(os.environ, _ANONYMOUS_USAGE_POLICY):
                outcome = dbtRunner().invoke(command)
        except Exception as exc:  # any dbt startup error is a transform failure
            raise TransformError(f"dbt {args[0]} failed to start: {exc}") from exc
        finally:
            self._release_dbt_resources()
        exception = getattr(outcome, "exception", None)
        if exception is not None:
            raise TransformError(f"dbt {args[0]} failed: {exception}") from exception
        command_result = getattr(outcome, "result", None)
        if not allow_failure and not bool(getattr(command_result, "success", True)):
            raise TransformError(f"dbt {args[0]} did not succeed; see {self._log_dir}")

    @staticmethod
    def _release_dbt_resources() -> None:
        """Close the in-process DuckDB connection and dbt log files.

        dbt-duckdb keeps a process-wide environment open after ``dbtRunner``
        returns and dbt's event logger replaces handlers without closing them.
        Releasing both keeps repeated in-process runs working and prevents a
        different-configuration lock on the same warehouse file (D18) as well as
        leaked file descriptors.
        """
        try:
            environment = DuckDBConnectionManager._ENV
            if environment is not None:
                environment.close()  # type: ignore[no-untyped-call]
            DuckDBConnectionManager._ENV = None
        except Exception:  # noqa: S110 - best-effort cleanup of a third-party singleton
            pass
        for name in _DBT_LOGGER_NAMES:
            logger = logging.getLogger(name)
            for handler in tuple(logger.handlers):
                handler.flush()
                handler.close()
                logger.removeHandler(handler)
